package com.example.pipecut.domain.exporter

import android.content.Context
import android.content.Intent
import com.example.pipecut.data.model.OptimizationResult
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object CuttingPlanExporter {

    fun generateTextPlan(result: OptimizationResult, projectName: String? = null): String {
        val u = result.unit
        val sdf = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault())
        val dateStr = sdf.format(Date(result.timestamp))
        val sb = StringBuilder()

        sb.appendLine("==================================================")
        sb.appendLine("              PIPECUT - CUTTING PLAN              ")
        sb.appendLine("==================================================")
        if (!projectName.isNullOrBlank()) {
            sb.appendLine("Project: $projectName")
        }
        sb.appendLine("Date: $dateStr")
        sb.appendLine("Unit: ${u.displayName}")
        sb.appendLine("Saw Blade Kerf: ${u.format(result.settings.sawKerf)}")
        sb.appendLine("End Trim: ${u.format(result.settings.endTrim)} ${if (result.settings.trimBothEnds) "(Both ends)" else "(Lead only)"}")
        if (result.settings.extraAllowancePerPiece > 0) {
            sb.appendLine("Piece Allowance: ${u.format(result.settings.extraAllowancePerPiece)}")
        }
        sb.appendLine("Min Reusable Length: ${u.format(result.settings.minReusableLength)}")
        sb.appendLine("--------------------------------------------------")
        sb.appendLine("SUMMARY SCORECARD")
        sb.appendLine("--------------------------------------------------")
        sb.appendLine("Stock Pipes Used:        ${result.totalStockPipesUsed}")
        sb.appendLine("Pieces Cut:              ${result.totalPiecesCut} of ${result.totalPiecesRequested}")
        sb.appendLine("Total Stock Consumed:    ${u.format(result.totalStockLengthConsumed)}")
        sb.appendLine("Total Useful Length:     ${u.format(result.totalUsefulLength)}")
        sb.appendLine("Total Blade Kerf Loss:   ${u.format(result.totalKerfLoss)}")
        sb.appendLine("Total Trim Loss:         ${u.format(result.totalTrimLoss)}")
        sb.appendLine("Reusable Offcuts:        ${result.reusableOffcutsCount} pcs (${u.format(result.totalReusableOffcutLength)})")
        sb.appendLine("Scrap Waste:             ${u.format(result.totalScrapWasteLength)} (${String.format(Locale.US, "%.1f", result.wastePercentage)}%)")
        sb.appendLine("Material Utilization:    ${String.format(Locale.US, "%.1f", result.materialUtilizationPercentage)}%")
        sb.appendLine("Total Usable Yield:      ${String.format(Locale.US, "%.1f", result.totalYieldPercentage)}%")

        if (result.hasUnfulfilled) {
            sb.appendLine()
            sb.appendLine("⚠️ WARNING: INSUFFICIENT STOCK FOR FOLLOWING PIECES:")
            for (un in result.unfulfilledCuts) {
                sb.appendLine(" - ${un.quantity}x ${un.label.ifBlank { "Piece" }} @ ${u.format(un.length)}")
            }
        }

        sb.appendLine()
        sb.appendLine("--------------------------------------------------")
        sb.appendLine("DETAILED CUTTING SEQUENCE PER PIPE")
        sb.appendLine("--------------------------------------------------")

        for (plan in result.plans) {
            sb.appendLine()
            sb.appendLine("PIPE #${plan.pipeIndex} - ${plan.stockLabel} [Total: ${u.format(plan.stockLength)}]")
            sb.appendLine("Utilization: ${String.format(Locale.US, "%.1f", plan.utilizationPercentage)}% | Total Pieces: ${plan.cuts.size}")
            if (plan.leadTrim > 0) {
                sb.appendLine("  [0.0 -> ${u.format(plan.leadTrim)}] Lead Trim (Cut off end)")
            }

            for (cut in plan.cuts) {
                val allowStr = if (cut.extraAllowance > 0) " (+${u.format(cut.extraAllowance)} allow)" else ""
                sb.appendLine("  Cut #${cut.sequenceNumber}: ${cut.label} -> Length: ${u.format(cut.length)}$allowStr")
                sb.appendLine("           Range: ${u.format(cut.startPosition)} to ${u.format(cut.endPosition)} | Kerf cut: ${u.format(cut.kerfAfter)}")
            }

            if (plan.trailTrim > 0) {
                sb.appendLine("  Trail Trim: ${u.format(plan.trailTrim)}")
            }

            val statusStr = if (plan.isReusableOffcut) "REUSABLE OFFCUT" else "SCRAP DROP"
            sb.appendLine("  Remaining Leftover: ${u.format(plan.leftoverLength)} [$statusStr]")
        }

        sb.appendLine()
        sb.appendLine("==================================================")
        sb.appendLine("Generated by PipeCut Android App - Offline & Fast")
        sb.appendLine("==================================================")

        return sb.toString()
    }

    fun generateCsv(result: OptimizationResult): String {
        val u = result.unit
        val sb = StringBuilder()
        sb.appendLine("PipeIndex,StockLabel,StockLength,CutSequence,PieceLabel,PieceLength,Allowance,EffectiveLength,StartPos,EndPos,KerfAfter,PipeUtilizationPercent,PipeLeftover,LeftoverType")

        for (plan in result.plans) {
            val leftoverType = if (plan.isReusableOffcut) "Reusable" else "Scrap"
            if (plan.cuts.isEmpty()) {
                sb.appendLine("${plan.pipeIndex},\"${plan.stockLabel}\",${plan.stockLength},,,,0,0,0,0,0,${plan.leftoverLength},$leftoverType")
            } else {
                for (cut in plan.cuts) {
                    sb.appendLine(
                        "${plan.pipeIndex},\"${plan.stockLabel}\",${plan.stockLength},${cut.sequenceNumber},\"${cut.label}\",${cut.length},${cut.extraAllowance},${cut.effectiveLength},${cut.startPosition},${cut.endPosition},${cut.kerfAfter},${String.format(Locale.US, "%.2f", plan.utilizationPercentage)},${plan.leftoverLength},$leftoverType"
                    )
                }
            }
        }

        return sb.toString()
    }

    fun shareText(context: Context, text: String, title: String = "Share PipeCut Plan") {
        val sendIntent = Intent().apply {
            action = Intent.ACTION_SEND
            putExtra(Intent.EXTRA_TEXT, text)
            putExtra(Intent.EXTRA_SUBJECT, title)
            type = "text/plain"
        }
        val shareIntent = Intent.createChooser(sendIntent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(shareIntent)
    }

    fun shareCsv(context: Context, csvText: String, title: String = "Share PipeCut CSV") {
        val sendIntent = Intent().apply {
            action = Intent.ACTION_SEND
            putExtra(Intent.EXTRA_TEXT, csvText)
            putExtra(Intent.EXTRA_SUBJECT, "PipeCut-Cutting-Plan.csv")
            type = "text/csv"
        }
        val shareIntent = Intent.createChooser(sendIntent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(shareIntent)
    }
}
